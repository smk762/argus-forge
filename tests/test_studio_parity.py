"""The parity fixture argus-studio checks its twins against (#45).

argus-studio keeps hand-written twins of forge's heuristics
(``suggestTrainingParams`` / ``datasetSizeStatus`` / ``DATASET_SIZE_GUIDE`` in
``frontend/src/components/curator/types.ts``) and of the kohya emitter (demo
mode's ``forgeDemo.ts``). Forge cannot run studio's TypeScript, so it publishes
what its own code answers for a grid of cases as ``schema/forge-parity.json``.
Studio pins that file like a wire schema (``frontend/schema/pins.json``) and its
tests fail when a twin answers differently; its daily wire-drift job re-pulls
it from forge's ``dev``, so a change here reaches studio as a failing PR or an
issue.

This test fails when the committed fixture no longer matches the code. After an
intentional heuristics or emitter change, regenerate it:

    UPDATE_PARITY=1 uv run --no-sync pytest tests/test_studio_parity.py

and sync studio's twins in the same breath.
"""

from __future__ import annotations

import json
import os
import shutil
import tomllib
from pathlib import Path

from conftest import ExportFactory

from argus_forge.core import forge_config
from argus_forge.heuristics import CATEGORY_LABELS, DATASET_SIZE_GUIDE, dataset_size_status, suggest_training_params
from argus_forge.models import TARGET_CATEGORIES, ForgeRequest

FIXTURE = Path(__file__).resolve().parent.parent / "schema" / "forge-parity.json"
PARITY_VERSION = "1.0"

# Every size-guide boundary (each category's low, hi and ideal band, and one
# either side), plus the rounding cases: 7 and 27 round up, 20 and 60 land on
# an exact .5, 0 and 333 are the floors.
COUNTS = sorted(
    {0, 1, 7, 20, 25, 27, 60, 200, 333}
    | {
        n + d
        for g in DATASET_SIZE_GUIDE.values()
        for n in (g.low, g.hi, *(int(x) for x in g.ideal.split("–")))
        for d in (-1, 0, 1)
    }
)
# What the demo builder renders: every category, at a small, a typical and a large set.
KOHYA_COUNTS = (1, 27, 333)
# Demo mode's trigger; forge's export_factory names the set "myset" too.
TRIGGER = "myset"
# forgeDemo.ts's DEMO_IMAGE_DIR: the export is rendered as if it lived there.
DEMO_IMAGE_DIR = "/data/out"


def _kohya(export_factory: ExportFactory, count: int, category: str) -> dict[str, dict]:
    export = export_factory(n=count, category=category, name=TRIGGER)
    result = forge_config(
        ForgeRequest(
            export_dir=str(export),
            trainer="kohya",
            dry_run=True,
            collect_captions=False,
            path_map={str(export): DEMO_IMAGE_DIR},
        )
    )
    shutil.rmtree(export)  # export_factory reuses the "myset" dir: the next case must not count these images
    by_name = {f.name.rsplit("/", 1)[-1]: f.content for f in result.files}
    # Parsed, not raw: the twin may differ in comments and in how it spells a float (1e-4 vs 0.0001).
    return {name: tomllib.loads(by_name[name]) for name in ("dataset.toml", "config.toml")}


def build_fixture(export_factory: ExportFactory) -> dict:
    return {
        "parity_version": PARITY_VERSION,
        "_comment": "Generated by argus-forge tests/test_studio_parity.py; do not edit. argus-studio pins this file.",
        "categories": {
            c: {
                "label": CATEGORY_LABELS[c],
                "size_guide": {
                    "ideal": DATASET_SIZE_GUIDE[c].ideal,
                    "low": DATASET_SIZE_GUIDE[c].low,
                    "hi": DATASET_SIZE_GUIDE[c].hi,
                },
            }
            for c in TARGET_CATEGORIES
        },
        "suggest_training_params": [
            {"count": n, "category": c, "params": suggest_training_params(n, c).model_dump(mode="json")}
            for c in TARGET_CATEGORIES
            for n in COUNTS
        ],
        "dataset_size_status": [
            {"count": n, "category": c, **dataset_size_status(n, c).model_dump(mode="json")}
            for c in TARGET_CATEGORIES
            for n in COUNTS
        ],
        "kohya": [
            {"count": n, "category": c, "trigger": TRIGGER, "files": _kohya(export_factory, n, c)}
            for c in TARGET_CATEGORIES
            for n in KOHYA_COUNTS
        ],
    }


def _dump(fixture: dict) -> str:
    return json.dumps(fixture, indent=2, ensure_ascii=False) + "\n"


def test_parity_fixture_is_current(export_factory: ExportFactory) -> None:
    text = _dump(build_fixture(export_factory))
    if os.environ.get("UPDATE_PARITY", "").lower() in ("1", "true", "yes"):
        FIXTURE.write_text(text, encoding="utf-8")
    assert FIXTURE.is_file(), "missing schema/forge-parity.json: run with UPDATE_PARITY=1"
    assert FIXTURE.read_text(encoding="utf-8") == text, (
        "schema/forge-parity.json is stale. If the heuristics or emitter change is intentional, regenerate with "
        "UPDATE_PARITY=1 and sync argus-studio's types.ts / forgeDemo.ts (studio's tests check them against it)."
    )


def test_fixture_kohya_matches_its_own_heuristics() -> None:
    """Each kohya case trains exactly the images it names (a generator that leaked images between cases would not)."""
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    for case in fixture["kohya"]:
        params = suggest_training_params(case["count"], case["category"])
        (subset,) = case["files"]["dataset.toml"]["datasets"][0]["subsets"]
        assert subset["num_repeats"] == params.repeats, case["category"]
        assert case["files"]["config.toml"]["network_dim"] == params.network_dim


def test_fixture_covers_every_category_and_boundary() -> None:
    """The grid argus-studio checks is the whole taxonomy, with each size-guide edge on both sides."""
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert set(fixture["categories"]) == set(TARGET_CATEGORIES)
    tones = {(r["category"], r["tone"]) for r in fixture["dataset_size_status"]}
    for c in TARGET_CATEGORIES:
        assert {(c, t) for t in ("empty", "low", "good", "high")} <= tones
    texts = {r["text"] for r in fixture["dataset_size_status"]}
    assert any("workable" in t for t in texts) and any("sweet spot for" in t for t in texts)
    assert {(r["category"], r["count"]) for r in fixture["kohya"]} == {
        (c, n) for c in TARGET_CATEGORIES for n in KOHYA_COUNTS
    }
